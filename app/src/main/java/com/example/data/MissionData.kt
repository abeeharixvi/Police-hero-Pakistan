package com.example.data

enum class MissionObjectiveState {
    REACH_LOCATION,
    INVESTIGATE_CLUE,
    QUESTION_WITNESS,
    SPOTTED_SUSPECT,
    CHASE_SUSPECT,
    ARREST_SUSPECT,
    RETURN_TO_STATION,
    COMPLETED,
    FAILED
}

data class MissionObjectiveStep(
    val state: MissionObjectiveState,
    val description: String,
    var isDone: Boolean = false
)

data class MissionData(
    val id: Int,
    val title: String,
    val crimeType: String,
    val briefing: String,
    val locationZone: String,
    val targetX: Float,
    val targetY: Float,
    val suspectId: String,
    val difficulty: Int, // 1 to 5 stars
    val rewardCash: Int,
    val rewardXp: Int,
    val optionalObjectiveDesc: String,
    val isVehicleChase: Boolean = false,
    val unlockLevel: Int = 1,
    var isCompleted: Boolean = false,
    var bestStars: Int = 0
) {
    fun createObjectiveSteps(): List<MissionObjectiveStep> {
        val steps = mutableListOf<MissionObjectiveStep>()
        steps.add(MissionObjectiveStep(MissionObjectiveState.REACH_LOCATION, "Travel to $locationZone"))
        steps.add(MissionObjectiveStep(MissionObjectiveState.INVESTIGATE_CLUE, "Investigate crime scene & examine clues"))
        if (id in listOf(11, 13, 14, 21, 24)) {
            steps.add(MissionObjectiveStep(MissionObjectiveState.QUESTION_WITNESS, "Interrogate nearby witness for suspect direction"))
        }
        steps.add(MissionObjectiveStep(MissionObjectiveState.SPOTTED_SUSPECT, "Locate and identify the fleeing suspect"))
        steps.add(
            MissionObjectiveStep(
                MissionObjectiveState.CHASE_SUSPECT,
                if (isVehicleChase) "Engage in vehicular pursuit and corner suspect vehicle" else "Pursue suspect and close distance"
            )
        )
        steps.add(MissionObjectiveStep(MissionObjectiveState.ARREST_SUSPECT, "Apprehend and secure suspect with handcuffs"))
        steps.add(MissionObjectiveStep(MissionObjectiveState.RETURN_TO_STATION, "Transport suspect back to Police Station"))
        return steps
    }
}

